"""Contrato que debe cumplir cualquier proveedor de datos SEO.

La app (rutas e interfaz) solo conoce estos métodos y las estructuras que devuelven
(ver `providers/dataforseo/mappers.py`). Cambiar de proveedor = implementar esta clase.
Cada método devuelve `{"data": ..., "meta": {...}}`, donde `meta` incluye el coste real
y si la respuesta salió de la caché. `confirm=True` autoriza una consulta cuyo coste
supera el umbral o aún es desconocido.
"""
from typing import Any, Protocol

Response = dict[str, Any]


class SEOProvider(Protocol):
    # Keywords
    def search_volume(self, keywords: list[str], *, location_code: int | None = None,
                      language_code: str | None = None, confirm: bool = False) -> Response: ...
    def related_keywords(self, keyword: str, *, depth: int | None = None, limit: int | None = None,
                         location_code: int | None = None, language_code: str | None = None,
                         confirm: bool = False) -> Response: ...
    def keyword_suggestions(self, keyword: str, *, limit: int | None = None, exact_match: bool = False,
                            location_code: int | None = None, language_code: str | None = None,
                            confirm: bool = False) -> Response: ...
    def keyword_difficulty(self, keywords: list[str], *, location_code: int | None = None,
                           language_code: str | None = None, confirm: bool = False) -> Response: ...
    def search_intent(self, keywords: list[str], *, confirm: bool = False) -> Response: ...

    # Dominios
    def domain_overview(self, target: str, **kw: Any) -> Response: ...
    def ranked_keywords(self, target: str, **kw: Any) -> Response: ...
    def competitors(self, target: str, **kw: Any) -> Response: ...
    def keyword_gap(self, target_1: str, target_2: str, **kw: Any) -> Response: ...
    def top_pages(self, target: str, **kw: Any) -> Response: ...
    def rank_history(self, target: str, **kw: Any) -> Response: ...
    def bulk_traffic(self, targets: list[str], **kw: Any) -> Response: ...

    # Backlinks
    def backlinks_summary(self, target: str, **kw: Any) -> Response: ...
    def backlinks(self, target: str, **kw: Any) -> Response: ...
    def referring_domains(self, target: str, **kw: Any) -> Response: ...
    def anchors(self, target: str, **kw: Any) -> Response: ...

    # SERP
    def serp_organic(self, keyword: str, **kw: Any) -> Response: ...
    def rank_check(self, keyword: str, domain: str, **kw: Any) -> Response: ...

    # Auditoría técnica
    def start_crawl(self, target: str, **kw: Any) -> Response: ...
    def list_crawls(self) -> Response: ...
    def crawl_summary(self, task_id: str, **kw: Any) -> Response: ...
    def crawl_pages(self, task_id: str, **kw: Any) -> Response: ...
    def crawl_broken_links(self, task_id: str, **kw: Any) -> Response: ...
    def crawl_broken_resources(self, task_id: str, **kw: Any) -> Response: ...
    def crawl_duplicate_tags(self, task_id: str, tag_type: str, **kw: Any) -> Response: ...
    def crawl_redirect_chains(self, task_id: str, **kw: Any) -> Response: ...
    def crawl_non_indexable(self, task_id: str, **kw: Any) -> Response: ...
    def instant_page(self, url: str, **kw: Any) -> Response: ...
    def lighthouse(self, url: str, **kw: Any) -> Response: ...

    # Cuenta
    def account(self, *, confirm: bool = False) -> Response: ...
